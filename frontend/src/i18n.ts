const STORAGE_KEY = "tera_lang";

export function getPreferredLanguage(): SupportedLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as SupportedLanguage;
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch (_) {}
  return "en";
}

export function setPreferredLanguage(lang: SupportedLanguage) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (_) {}
}

export function t(key: string, lang: SupportedLanguage = getPreferredLanguage()): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

